// src/render/fog-sky-direction.js — 雾色融入天空的**方向换算纯函数**（v1.59，three-free）
//
// 为什么单独成模块：TSL 节点无法在单测里求值（GPU 才求），但「视线方向 → 用于采样天空盒
// 的方向」这段换算是有对错可言的逻辑（见下），必须能被 Tier 1 单测钉住。
// `materials.js` 的 TSL 实现与本文件**同构**（红线 1：不得各写一份阈值/钳制规则）——
// 数值常量（Y_FLOOR_EPS）从这里 import，不在着色器里另写字面量。
//
// 关键规则：**俯角（y ≤ 0）一律归到地平线带，只看方位角**。
//   直接用完整视线方向会让「往下看」时采样到立方图的天底那半张（实测白天 negy 均值
//   [97,125,186] vs 地平线 [207,216,232]）→ 俯视时雾色反而变暗（实测 G −17 / B −12，
//   方向是反的）。物理上远处地形该淡入的是**地平线处的天空色**：空气被上方光照射，
//   不是被地面照亮。保留水平分量就把方位角差异留下了 —— 那才是本功能的价值。

/**
 * 地平线带的最小 y 偏移量。俯角/水平视线（y ≤ 0）的 y 一律取此值 → 永远贴地平线，
 * 不会采样到天底那半张图。**同时兼作除零保护**（水平分量与 y 同时为零时长度仍 > 0）。
 * ⚠️ 着色器侧必须用同一个值（`materials.js` import 本常量，不写字面量）。
 */
export const FOG_SKY_Y_FLOOR_EPS = 1e-5;

/**
 * 把「片元 → 相机」的视线方向换算成用于采样天空盒的方向。
 *
 * 变换 = ① 俯角（y ≤ 0）一律拉回地平线带 ② 零向量保护 ③ 归一化。
 *
 * ⚠️ **为什么俯角不看深浅、一律归到地平线同一条带**：
 *   远处地形（雾里的方块）总是落在视线水平线上方一点点的位置，俯视时你看到的**近景**
 *   根本不在雾带（雾从 96 格才开始）。所以雾色要的永远是「地平线那里是什么颜色」，
 *   而不是「我眼睛朝下多少度」。
 * ⚠️ **为什么不能直接置 y=ε、而是保留水平分量**：水平分量的**方向**（即方位角）
 *   正是本功能的价值：朝东看与朝西看的天色不同，雾色得跟着变。
 * ⚠️ **垂直俯视（水平分量为零）没有方位角可保** —— 这是数学上无法修复的信息缺失。
 *   零向量保护：直接返回“天顶”不可取（实测会让垂直俯视时雾色变暗），而任选一个方位
 *   也是错的。选**地平的 +x 方向**作为确定性兼就，因为雾带本来就在正前方水平方向。
 *
 * @param {number} x @param {number} y @param {number} z 视线方向（无需预先归一化）
 * @returns {[number, number, number]} 单位向量
 */
export function fogSkySampleDir(x, y, z) {
  const horiz = Math.hypot(x, z);
  // 零向量保护：垂直俯视/仰视时水平分量为零 → 方位角无从确定。
  // 取 +x 作为确定性兼就（不能返回 y=1 的天顶 —— 实测会让俯视雾色反向变暗）。
  // ⚠️ 仰视（y>0）走下面的归一化分支，不算需此保护。
  const [hx, hz] = (horiz < 1e-9 && y <= 0) ? [1, 0] : [x, z];
  // 仰视（y > 0）：保留原方向（只归一化）；俯角/水平（y ≤ 0）：y 归到 ε（贴地平线）。
  const sy = y > 0 ? y : FOG_SKY_Y_FLOOR_EPS;
  const len = Math.hypot(hx, sy, hz);
  return [hx / len, sy / len, hz / len];
}
